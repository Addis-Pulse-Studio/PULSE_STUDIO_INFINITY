"""The Pulse Studio Infinity example graphs: built, current, and wired as a loop.

Both are generated by tools/build_infinity_workflows.py, so the first test is
that the committed files are exactly what the builder writes -- a hand edit to a
shipped graph is otherwise invisible until someone rebuilds and the diff surprises
them. The rest check the one shape that makes the loop a loop: the Loop node's
handle reaching the shot, the render and the observer, and the slate set the way
a chain of beats needs it.
"""

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

from comfyui_pulse_studio.pulse_director.scripted_provider import parse_script
from comfyui_pulse_studio.pulse_memory import DirectedShotPlan
from tests.test_js_guard import js_widget_names

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "example_workflows"
GRAPHS = ("PulseInfinity_Scripted.json", "PulseInfinity_ClosedLoop.json")


def _builder():
    spec = importlib.util.spec_from_file_location(
        "build_infinity_workflows", ROOT / "tools" / "build_infinity_workflows.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _load(name):
    return json.loads((FOLDER / name).read_text(encoding="utf-8"))


def _by_type(doc, node_type):
    return [n for n in doc["nodes"] if n["type"] == node_type]


def _one(doc, node_type):
    found = _by_type(doc, node_type)
    assert len(found) == 1, "%s: expected one %s, found %d" % (doc["id"], node_type, len(found))
    return found[0]


def _links_into(doc, node, input_name):
    slot = next(i for i, s in enumerate(node["inputs"]) if s["name"] == input_name)
    return [l for l in doc["links"] if l[3] == node["id"] and l[4] == slot]


def _source_type(doc, node, input_name):
    links = _links_into(doc, node, input_name)
    if not links:
        return None
    by_id = {n["id"]: n for n in doc["nodes"]}
    return by_id[links[0][1]]["type"]


def _widget(node, name):
    return node["widgets_values"][js_widget_names(node["type"]).index(name)]


class TestTheGraphsAreCurrent(unittest.TestCase):
    def test_the_committed_files_are_what_the_builder_writes(self):
        with tempfile.TemporaryDirectory() as out:
            _builder().build(out)
            for name in GRAPHS:
                with self.subTest(graph=name):
                    self.assertEqual((Path(out) / name).read_text(encoding="utf-8"),
                                     (FOLDER / name).read_text(encoding="utf-8"),
                                     "%s is stale: run tools/build_infinity_workflows.py"
                                     % name)


class TestTheLoopIsWired(unittest.TestCase):
    def test_the_handle_reaches_the_shot_the_render_and_the_observer(self):
        for name in GRAPHS:
            with self.subTest(graph=name):
                doc = _load(name)
                for node_type, socket in (("PulseDynamicShot", "infinity"),
                                          ("PulseInfinityRender", "infinity"),
                                          ("PulseObserver", "infinity")):
                    self.assertEqual(_source_type(doc, _one(doc, node_type), socket),
                                     "PulseInfinityLoopController", node_type)
                slate = _one(doc, "PulseSlate")
                self.assertEqual(_source_type(doc, slate, "shots.shot_1"), "PulseDynamicShot")
                render = _one(doc, "PulseInfinityRender")
                self.assertEqual(_source_type(doc, render, "timeline"), "PulseSlate")
                self.assertEqual(_source_type(doc, _one(doc, "PulseObserver"), "beat"),
                                 "PulseInfinityRender")
                self.assertEqual(_source_type(doc, _one(doc, "PulseInfinityLoopController"),
                                              "cast.cast_1"), "PulseCharacter")

    def test_the_slate_is_set_for_a_chain_of_beats(self):
        for name in GRAPHS:
            with self.subTest(graph=name):
                slate = _one(_load(name), "PulseSlate")
                values = slate["widgets_values"]
                names = js_widget_names("PulseSlate")
                self.assertEqual(values[names.index("continuity")], "none",
                                 "a frame-pinning mode puts every carried beat on fl2va, "
                                 "which drops the cast references")
                self.assertIs(values[names.index("carry_audio")], False,
                              "a 4 s audio tail outlasts the pad after a line and spills "
                              "speech into the next beat")
                self.assertNotIn("@", values[names.index("global_prompt")])

    def test_cast_voices_are_timbre_not_lip_sync(self):
        """A lip_sync voice sits on the film clock, which restarts every beat."""
        for name in GRAPHS:
            with self.subTest(graph=name):
                for voice in _by_type(_load(name), "PulseVoice"):
                    self.assertEqual(_widget(voice, "role"), "voice_timbre")

    def test_the_observer_and_the_loop_report_somewhere(self):
        for name in GRAPHS:
            with self.subTest(graph=name):
                doc = _load(name)
                wired = {l[1] for l in doc["links"]}
                self.assertIn(_one(doc, "PulseObserver")["id"], wired)


class TestTheScriptedGraph(unittest.TestCase):
    def setUp(self):
        self.doc = _load("PulseInfinity_Scripted.json")
        self.loop = _one(self.doc, "PulseInfinityLoopController")

    def test_it_needs_no_model_director(self):
        self.assertEqual(_widget(self.loop, "director_backend"), "scripted")

    def test_every_scripted_beat_honours_the_contract(self):
        plans, problems = parse_script(_widget(self.loop, "script"))
        self.assertEqual(problems, [])
        self.assertEqual(len(plans), _widget(self.loop, "max_beats"))
        for index, data in enumerate(plans, 1):
            plan, plan_problems = DirectedShotPlan.from_dict(dict(data, shot_index=index),
                                                             cast_names=["Alice"])
            self.assertEqual(plan_problems, [], "beat %d" % index)


class TestTheClosedLoopGraph(unittest.TestCase):
    def setUp(self):
        self.doc = _load("PulseInfinity_ClosedLoop.json")

    def test_the_director_comes_from_the_config(self):
        loop = _one(self.doc, "PulseInfinityLoopController")
        self.assertEqual(_widget(loop, "director_backend"), "from_config")

    def test_hyperflow_patches_the_model_both_nodes_sample_with(self):
        hyperflow = _one(self.doc, "HyperFlowLoRALoader")
        for node_type in ("PulseSlate", "PulseInfinityRender"):
            links = _links_into(self.doc, _one(self.doc, node_type), "model")
            self.assertEqual(links[0][1], hyperflow["id"], node_type)
        recipe = _one(self.doc, "PulseRecipe")
        self.assertEqual(recipe["widgets_values"][1], "hyperflow_8step")

    def test_fish_s2_sits_behind_the_lazy_dialogue_input(self):
        tts = _one(self.doc, "FishS2VoiceCloneTTS")
        shot = _one(self.doc, "PulseDynamicShot")
        self.assertEqual(_links_into(self.doc, shot, "dialogue_audio")[0][1], tts["id"])
        for socket, output in (("text", "tts_text"), ("reference_audio", "speaker_voice"),
                               ("seed", "seed")):
            link = _links_into(self.doc, tts, socket)[0]
            loop = _one(self.doc, "PulseInfinityLoopController")
            self.assertEqual((link[1], loop["outputs"][link[2]]["name"]),
                             (loop["id"], output))
        text_slot = next(s for s in tts["inputs"] if s["name"] == "text")
        self.assertEqual(text_slot.get("widget"), {"name": "text"})
        self.assertIs(tts["widgets_values"][13], False, "keep_model_loaded off: S2 is ~20 GB")


if __name__ == "__main__":
    unittest.main()
